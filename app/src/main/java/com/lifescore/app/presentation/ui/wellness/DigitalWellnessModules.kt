// 1. TASK BREAKTHROUGH (AI 3-Priority Decomposer)
// ==========================================
data class SubPriorityStep(
    val stepNumber: Int,
    val title: String,
    val minutes: Int,
    val isDone: Boolean = false
)

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun TaskBreakthroughScreen(
    onBack: () -> Unit = {}
) {
    var rawAssignment by remember { mutableStateOf("") }
    var isDecomposing by remember { mutableStateOf(false) }
    var breakdownSteps by remember {
        mutableStateOf(
            listOf(
                SubPriorityStep(1, "Clarify Core Requirements & Create 1-Page Outline", 15),
                SubPriorityStep(2, "Draft 3 Core Arguments / Skeleton Functions", 25),
                SubPriorityStep(3, "Polish & Verification Test", 10)
            )
        )
    }
    var hasGenerated by remember { mutableStateOf(true) }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Column {
                        Text("⚡ Task Breakthrough", fontWeight = FontWeight.Bold)
                        Text(
                            "AI 3-Priority Decomposer • Beats Overwhelm",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.Default.ArrowBack, contentDescription = "Back")
                    }
                }
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            Card(
                shape = RoundedCornerShape(16.dp),
                colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f))
            ) {
                Column(modifier = Modifier.padding(16.dp)) {
                    Text(
                        "Enter your intimidating task or assignment:",
                        fontWeight = FontWeight.Bold,
                        style = MaterialTheme.typography.bodyMedium
                    )
                    Spacer(Modifier.height(8.dp))
                    OutlinedTextField(
                        value = rawAssignment,
                        onValueChange = { rawAssignment = it },
                        placeholder = { Text("e.g., Complete 20-page research thesis literature review") },
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(12.dp),
                        minLines = 2
                    )
                    Spacer(Modifier.height(12.dp))
                    Button(
                        onClick = {
                            isDecomposing = true
                            hasGenerated = true
                            isDecomposing = false
                        },
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(10.dp)
                    ) {
                        Icon(Icons.Default.Star, contentDescription = null)
                        Spacer(Modifier.width(8.dp))
                        Text("Break Down into 3 High-Impact Steps (+30 XP)")
                    }
                }
            }

            if (hasGenerated) {
                Text(
                    "🎯 Your 3 Non-Negotiable Priorities",
                    style = MaterialTheme.typography.titleMedium,
                    fontWeight = FontWeight.Bold
                )

                breakdownSteps.forEachIndexed { index, step ->
                    Card(
                        shape = RoundedCornerShape(16.dp),
                        colors = CardDefaults.cardColors(
                            containerColor = if (step.isDone) MaterialTheme.colorScheme.secondaryContainer.copy(alpha = 0.4f) else MaterialTheme.colorScheme.surface
                        ),
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        Row(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(16.dp),
                            verticalAlignment = Alignment.CenterVertically,
                            horizontalArrangement = Arrangement.SpaceBetween
                        ) {
                            Row(verticalAlignment = Alignment.CenterVertically, modifier = Modifier.weight(1f)) {
                                Box(
                                    contentAlignment = Alignment.Center,
                                    modifier = Modifier
                                        .size(32.dp)
                                        .clip(CircleShape)
                                        .background(MaterialTheme.colorScheme.primaryContainer)
                                ) {
                                    Text("${step.stepNumber}", fontWeight = FontWeight.Black, color = MaterialTheme.colorScheme.primary)
                                }
                                Spacer(Modifier.width(12.dp))
                                Column {
                                    Text(
                                        step.title,
                                        fontWeight = FontWeight.SemiBold,
                                        style = MaterialTheme.typography.bodyMedium
                                    )
                                    Text(
                                        "⏱️ ~${step.minutes} mins",
                                        style = MaterialTheme.typography.labelSmall,
                                        color = MaterialTheme.colorScheme.onSurfaceVariant
                                    )
                                }
                            }

                            Checkbox(
                                checked = step.isDone,
                                onCheckedChange = { isChecked ->
                                    breakdownSteps = breakdownSteps.toMutableList().also {
                                        it[index] = step.copy(isDone = isChecked)
                                    }
                                }
                            )
                        }
                    }
                }
            }
        }
    }
}

