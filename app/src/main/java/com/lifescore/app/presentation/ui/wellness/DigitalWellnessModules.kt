// 2. THOUGHT BREAK (CBT Cognitive Reframing)
// ==========================================
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ThoughtBreakScreen(
    viewModel: ScreenTimeViewModel,
    onBack: () -> Unit = {}
) {
    var automaticThought by remember { mutableStateOf("") }
    var selectedDistortion by remember { mutableStateOf("Catastrophizing") }
    var evidenceAgainst by remember { mutableStateOf("") }
    var reframedThought by remember { mutableStateOf("") }
    var reliefRating by remember { mutableStateOf(8f) }
    var isSubmitted by remember { mutableStateOf(false) }

    val distortions = listOf(
        "Catastrophizing",
        "All-or-Nothing",
        "Mind Reading",
        "Emotional Reasoning",
        "Overgeneralizing"
    )

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Column {
                        Text("🧠 Thought Break", fontWeight = FontWeight.Bold)
                        Text(
                            "CBT Cognitive Reframing • Break Stuck Loops",
                            style = MaterialTheme.typography.bodySmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.Default.ArrowBack, contentDescription = "Back")
                    }
                }
            )
        }
    ) { padding ->
        LazyColumn(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            item {
                Card(
                    shape = RoundedCornerShape(18.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.primaryContainer.copy(alpha = 0.5f))
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Text("1. What automatic negative thought is bothering you?", fontWeight = FontWeight.Bold)
                        Spacer(Modifier.height(8.dp))
                        OutlinedTextField(
                            value = automaticThought,
                            onValueChange = { automaticThought = it },
                            placeholder = { Text("e.g., 'If I don't finish this perfectly today, my entire project will fail.'") },
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            minLines = 2
                        )
                    }
                }
            }

            item {
                Text("2. Identify the Cognitive Distortion:", fontWeight = FontWeight.Bold)
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.spacedBy(8.dp)
                ) {
                    distortions.take(3).forEach { dist ->
                        FilterChip(
                            selected = selectedDistortion == dist,
                            onClick = { selectedDistortion = dist },
                            label = { Text(dist, fontSize = 12.sp) }
                        )
                    }
                }
            }

            item {
                Card(
                    shape = RoundedCornerShape(18.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant.copy(alpha = 0.5f))
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Text("3. Evidence against this thought:", fontWeight = FontWeight.Bold)
                        Spacer(Modifier.height(8.dp))
                        OutlinedTextField(
                            value = evidenceAgainst,
                            onValueChange = { evidenceAgainst = it },
                            placeholder = { Text("e.g., I've made steady progress every day. Iteration matters more than immediate perfection.") },
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            minLines = 2
                        )
                    }
                }
            }

            item {
                Card(
                    shape = RoundedCornerShape(18.dp),
                    colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface)
                ) {
                    Column(modifier = Modifier.padding(16.dp)) {
                        Text("4. Balanced & Empowering Reframe:", fontWeight = FontWeight.Bold)
                        Spacer(Modifier.height(8.dp))
                        OutlinedTextField(
                            value = reframedThought,
                            onValueChange = { reframedThought = it },
                            placeholder = { Text("e.g., 'I will focus on one clean step today. Progress is compound, not instantaneous.'") },
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp),
                            minLines = 2
                        )
                        Spacer(Modifier.height(12.dp))
                        Text("Emotional Relief: ${reliefRating.toInt()} / 10", style = MaterialTheme.typography.bodySmall)
                        Slider(
                            value = reliefRating,
                            onValueChange = { reliefRating = it },
                            valueRange = 1f..10f,
                            steps = 9
                        )
                        Spacer(Modifier.height(8.dp))
                        Button(
                            onClick = {
                                viewModel.submitThoughtBreak(
                                    automaticThought.ifBlank { "Unexamined friction thought" },
                                    selectedDistortion,
                                    evidenceAgainst.ifBlank { "Evidence of past capability" },
                                    reframedThought.ifBlank { "Balanced realistic perspective" },
                                    reliefRating.toInt()
                                )
                                isSubmitted = true
                            },
                            modifier = Modifier.fillMaxWidth(),
                            shape = RoundedCornerShape(12.dp)
                        ) {
                            Icon(Icons.Default.Check, contentDescription = null)
                            Spacer(Modifier.width(8.dp))
                            Text("Save Reframe (+40 XP Mental Health)")
                        }
                    }
                }
            }
        }
    }
}
